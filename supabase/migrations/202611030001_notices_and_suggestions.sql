create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 100),
  body text not null check (char_length(trim(body)) between 1 and 3000),
  image_url text,
  image_storage_path text,
  is_featured boolean not null default false,
  like_count integer not null default 0 check (like_count >= 0),
  created_by uuid not null references public.profiles(id) on delete restrict,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notice_likes (
  notice_id bigint not null references public.notices(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (notice_id, user_id)
);

create table if not exists public.suggestions (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete restrict,
  author_name text not null check (char_length(trim(author_name)) between 1 and 80),
  title text not null check (char_length(trim(title)) between 2 and 100),
  body text not null check (char_length(trim(body)) between 5 and 3000),
  is_private boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notices_published_at_idx on public.notices (published_at desc);
create index if not exists suggestions_created_at_idx on public.suggestions (created_at desc);

alter table public.notices enable row level security;
alter table public.notice_likes enable row level security;
alter table public.suggestions enable row level security;

