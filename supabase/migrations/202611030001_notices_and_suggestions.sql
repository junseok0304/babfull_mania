create or replace function public.sync_notice_like_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.notices set like_count = like_count + 1 where id = new.notice_id;
    return new;
  end if;
  update public.notices set like_count = greatest(0, like_count - 1) where id = old.notice_id;
  return old;
end;
$$;

drop trigger if exists notice_likes_count_after_insert on public.notice_likes;
create trigger notice_likes_count_after_insert
after insert on public.notice_likes
for each row execute function public.sync_notice_like_count();

drop trigger if exists notice_likes_count_after_delete on public.notice_likes;
create trigger notice_likes_count_after_delete
after delete on public.notice_likes
for each row execute function public.sync_notice_like_count();

create or replace function public.toggle_notice_like(target_notice_id bigint)
returns table (liked boolean, new_like_count integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  active_user boolean;
begin
  select p.is_active into active_user from public.profiles p where p.id = auth.uid();
  if coalesce(active_user, false) is false then raise exception '활성 사용자만 좋아요를 누를 수 있습니다.'; end if;
  if not exists (select 1 from public.notices n where n.id = target_notice_id) then raise exception '공지사항을 찾지 못했습니다.'; end if;

  delete from public.notice_likes l where l.notice_id = target_notice_id and l.user_id = auth.uid();
  if found then
    return query select false, n.like_count from public.notices n where n.id = target_notice_id;
    return;
  end if;

  insert into public.notice_likes (notice_id, user_id) values (target_notice_id, auth.uid());
  return query select true, n.like_count from public.notices n where n.id = target_notice_id;
end;
$$;

create or replace function public.create_suggestion(
  suggestion_title text,
  suggestion_body text,
  private_post boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_record public.profiles%rowtype;
  created_id bigint;
begin
  select * into profile_record from public.profiles where id = auth.uid();
  if profile_record.id is null or not profile_record.is_active then raise exception '로그인한 활성 사용자만 건의할 수 있습니다.'; end if;
  if nullif(trim(profile_record.name), '') is null then raise exception '실명 프로필을 확인할 수 없습니다.'; end if;
  if char_length(trim(coalesce(suggestion_title, ''))) not between 2 and 100 then raise exception '제목은 2자 이상 100자 이하로 입력해주세요.'; end if;
  if char_length(trim(coalesce(suggestion_body, ''))) not between 5 and 3000 then raise exception '내용은 5자 이상 3000자 이하로 입력해주세요.'; end if;

  insert into public.suggestions (author_id, author_name, title, body, is_private)
  values (profile_record.id, trim(profile_record.name), trim(suggestion_title), trim(suggestion_body), coalesce(private_post, false))
  returning id into created_id;
  return created_id;
end;
$$;

